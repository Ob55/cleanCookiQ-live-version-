// One-off generator for src/lib/countyBounds.ts: bounding boxes of Kenya's 47
// counties (OSM admin_level=4) in a single Overpass query.
// Run: node scripts/gen-county-bounds.mjs
// Output is committed so the app never calls OSM during validation.
import { writeFileSync } from "node:fs";

const COUNTIES = [
  "Baringo", "Bomet", "Bungoma", "Busia", "Elgeyo-Marakwet", "Embu",
  "Garissa", "Homa Bay", "Isiolo", "Kajiado", "Kakamega", "Kericho",
  "Kiambu", "Kilifi", "Kirinyaga", "Kisii", "Kisumu", "Kitui",
  "Kwale", "Laikipia", "Lamu", "Machakos", "Makueni", "Mandera",
  "Marsabit", "Meru", "Migori", "Mombasa", "Murang'a", "Nairobi",
  "Nakuru", "Nandi", "Narok", "Nyamira", "Nyandarua", "Nyeri",
  "Samburu", "Siaya", "Taita-Taveta", "Tana River", "Tharaka-Nithi",
  "Trans Nzoia", "Turkana", "Uasin Gishu", "Vihiga", "Wajir", "West Pokot",
];

const key = (s) => s.toLowerCase().replace(/county/g, "").replace(/[^a-z]/g, "");
const query =
  '[out:json][timeout:90];area["ISO3166-1"="KE"][admin_level=2]->.k;' +
  'rel(area.k)["admin_level"="4"]["boundary"="administrative"];out bb tags;';

const res = await fetch("https://overpass-api.de/api/interpreter", {
  method: "POST",
  headers: { "User-Agent": "CleanCookIQ county-bounds generator" },
  body: new URLSearchParams({ data: query }),
});
const { elements } = await res.json();
const byKey = new Map(elements.map((e) => [key(e.tags.name), e.bounds]));

const out = {};
for (const c of COUNTIES) {
  const b = byKey.get(key(c));
  if (!b) throw new Error(`No boundary for ${c}`);
  out[c] = [b.minlat, b.minlon, b.maxlat, b.maxlon];
}

const body = Object.entries(out)
  .map(([k, v]) => `  ${JSON.stringify(k)}: [${v.map((x) => x.toFixed(4)).join(", ")}],`)
  .join("\n");
writeFileSync(
  "src/lib/countyBounds.ts",
  `// Generated by scripts/gen-county-bounds.mjs from OpenStreetMap. Do not hand-edit.\n` +
    `// [south, west, north, east] in decimal degrees.\n` +
    `export const COUNTY_BOUNDS: Record<string, [number, number, number, number]> = {\n${body}\n};\n`,
);
console.log(`wrote ${Object.keys(out).length} counties`);
